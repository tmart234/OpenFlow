"""
Travel-time precipitation zones for each station (basin_zones.json).

Rain that matters for a river gauge is rain on its CONTRIBUTING AREA, and
when it arrives depends on how far up the river network it fell. A HUC level
on its own is the wrong unit: HUC2 13 is the whole Rio Grande to the Gulf,
HUC4 1301 includes the San Luis Valley's Closed Basin (which never drains to
the river), and a gauge's own HUC8 extends downstream of it.

So each station's contributing area is taken from the USGS NLDI network
(upstream HUC12 pour points; non-contributing closed basins are excluded by
construction) and split by river distance to the gauge:

    local : HUC12s whose outlet is <= zone_km[0] river-km upstream (~< 1 day)
    mid   : <= zone_km[1]                                           (~1-3 days)
    far   : everything further upstream                             (~3+ days)

plus an `ungauged` area: the part of the basin NOT upstream of the station's
registered upstream gauges (upstream_gauges.json). The routing forecaster
turns rain on the ungauged area into a local-inflow term, because the
upstream gauges' own NWS forecasts already account for the gauged part.

basin_zones.json is generated by build_basin_zones.py (needs shapely +
network) and committed, so training and inference only need the light,
dependency-free helpers in this module: zone polygons as plain rings, and
area-weighted forecast sample points carrying their NWS gridpoint id.
"""

import json
import os
from typing import Dict, Optional

import numpy as np

ZONES = ('local', 'mid', 'far')
DEFAULT_ZONE_KM = (100, 250)
ZONES_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'basin_zones.json')

# Rain/snow partition by daily (or hourly) mean air temperature: all snow at
# or below SNOW_T_C, all rain at or above RAIN_T_C, linear in between. One
# rule for gridMET history, NWS forecasts and mobile inference, so the model
# never sees two definitions of "rain".
SNOW_T_C = -1.0
RAIN_T_C = 3.0

CFS_PER_M3S = 35.3146667


def load_zones(path: Optional[str] = None) -> Dict[str, dict]:
    if not os.path.exists(path or ZONES_PATH):
        return {}
    with open(path or ZONES_PATH) as f:
        raw = json.load(f)
    return {k: v for k, v in raw.items() if not k.startswith('_')}


def station_zones(site_id: str, zones: Optional[Dict[str, dict]] = None) -> Optional[dict]:
    zones = zones if zones is not None else load_zones()
    cfg = zones.get(site_id)
    if not cfg or not cfg.get('zones'):
        return None
    return cfg


def liquid_fraction(temp_c) -> np.ndarray:
    """Fraction of precipitation falling as rain at mean air temperature temp_c (deg C)."""
    t = np.asarray(temp_c, dtype=float)
    return np.clip((t - SNOW_T_C) / (RAIN_T_C - SNOW_T_C), 0.0, 1.0)


def points_in_rings(lon, lat, rings) -> np.ndarray:
    """
    Vectorised even-odd point-in-polygon test against a list of rings
    ([[lon, lat], ...]); exterior rings and holes alike, so holes punch out.
    Returns a bool array shaped like lon.
    """
    lon = np.asarray(lon, dtype=float)
    lat = np.asarray(lat, dtype=float)
    inside = np.zeros(lon.shape, dtype=bool)
    for ring in rings or []:
        r = np.asarray(ring, dtype=float)
        if len(r) < 3:
            continue
        x1, y1 = r[:, 0], r[:, 1]
        x2, y2 = np.roll(x1, -1), np.roll(y1, -1)
        for ax, ay, bx, by in zip(x1, y1, x2, y2):
            if ay == by:
                continue
            crosses = (ay > lat) != (by > lat)
            x_at = ax + (lat - ay) * (bx - ax) / (by - ay)
            inside ^= crosses & (lon < x_at)
    return inside


def bbox(cfg: dict, pad: float = 0.05):
    """(south, north, west, east) covering every zone polygon, padded."""
    xs, ys = [], []
    for z in list(cfg.get('zones', {}).values()) + [cfg.get('ungauged') or {}]:
        for ring in z.get('rings', []):
            r = np.asarray(ring, dtype=float)
            xs.extend(r[:, 0])
            ys.extend(r[:, 1])
    if not xs:
        raise ValueError("station has no zone polygons")
    return min(ys) - pad, max(ys) + pad, min(xs) - pad, max(xs) + pad


def grid_masks(cfg: dict, lon2d: np.ndarray, lat2d: np.ndarray) -> Dict[str, np.ndarray]:
    """Bool masks on a lon/lat grid for each zone and for the ungauged area."""
    masks = {z: points_in_rings(lon2d, lat2d, cfg['zones'].get(z, {}).get('rings', []))
             for z in ZONES}
    masks['ungauged'] = points_in_rings(lon2d, lat2d, (cfg.get('ungauged') or {}).get('rings', []))
    return masks


def point_weights(cfg: dict) -> Dict[str, np.ndarray]:
    """
    Normalised weights over cfg['points'] for each zone and for the ungauged
    area (each weight vector sums to 1, or is all-zero when the area has no
    sample point).
    """
    pts = cfg.get('points', [])
    w = np.array([p.get('w', 1.0) for p in pts], dtype=float)
    out = {}
    for z in ZONES:
        m = np.array([p.get('zone') == z for p in pts], dtype=bool)
        out[z] = _normalise(w * m)
    m = np.array([bool(p.get('ungauged')) for p in pts], dtype=bool)
    out['ungauged'] = _normalise(w * m)
    return out


def _normalise(w: np.ndarray) -> np.ndarray:
    s = w.sum()
    return w / s if s > 0 else w


def mm_per_hour_to_cfs(mm_per_hour, area_km2: float):
    """Areal rain rate (mm/h over area_km2) as a volumetric flux in cfs."""
    return np.asarray(mm_per_hour, dtype=float) * float(area_km2) * 1e3 / 3600.0 * CFS_PER_M3S
